// ============================================================
// main.c
// HPS Radar Controller Application
// COE838 — FMCW Radar Range-Doppler SoC
//
// Runs on ARM Cortex-A9 under Yocto Linux
// Compiled in DS-5 with DS-5 GCC toolchain
//
// Flow:
//   1. mmap the two bridges into userspace virtual memory
//   2. Generate synthetic I/Q radar frame (known targets)
//   3. Write frame into FPGA input SRAM via full bridge
//   4. Configure and start accelerator via lightweight bridge
//   5. Poll STATUS until DONE
//   6. Read results from output SRAM
//   7. Run software reference (pure C FFT + magnitude)
//   8. Compare peaks, print timing and speedup
// ============================================================

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <math.h>
#include <time.h>
#include <fcntl.h>
#include <unistd.h>
#include <sys/mman.h>

// Altera hwlib — provides alt_read_word / alt_write_word
// Include path set in DS-5 project properties
#include "hwlib.h"
#include "socal/socal.h"
#include "socal/hps.h"

// QSys-generated header — contains base addresses of your components
// Generated by: sopc-create-header-files in NIOS II shell
#include "hps_0.h"

// ============================================================
// Bridge base addresses (from Lab 3 Table I)
// ============================================================
#define LW_BRIDGE_BASE    0xFF200000   // Lightweight HPS-to-FPGA
#define LW_BRIDGE_SPAN    0x00200000   // 2MB span
#define HF_BRIDGE_BASE    0xC0000000   // Full HPS-to-FPGA
#define HF_BRIDGE_SPAN    0x3C000000   // 960MB span

// ============================================================
// Control register offsets (word-addressed from ctrl slave base)
// Must match avalon_ctrl_slave.v localparam addresses
// ============================================================
#define CTRL_OFFSET       (0 * 4)    // 0x00
#define STATUS_OFFSET     (1 * 4)    // 0x04
#define NR_OFFSET         (2 * 4)    // 0x08
#define ND_OFFSET         (3 * 4)    // 0x0C
#define CYCLES_OFFSET     (4 * 4)    // 0x10

// CTRL register bits
#define CTRL_START_BIT    (1 << 0)
#define CTRL_RESET_BIT    (1 << 1)

// STATUS register bits
#define STATUS_BUSY_BIT   (1 << 0)
#define STATUS_DONE_BIT   (1 << 1)

// ============================================================
// SRAM offsets from full bridge base
// Must match QSys base address assignments
// ============================================================
#define INPUT_SRAM_OFFSET  0x00000000  // 64KB input buffer
#define OUTPUT_SRAM_OFFSET 0x00010000  // 64KB output buffer

// ============================================================
// Radar frame parameters
// ============================================================
#define NR    256     // samples per chirp (range FFT length)
#define ND    64      // chirps per frame  (Doppler dimension)
#define PI    3.14159265358979323846

// ============================================================
// MMIO helper macros
// These wrap alt_write_word / alt_read_word from hwlib
// ============================================================
#define MMIO_WRITE(base, offset, val) \
    alt_write_word(((uint8_t*)(base) + (offset)), (val))

#define MMIO_READ(base, offset) \
    alt_read_word(((uint8_t*)(base) + (offset)))

// ============================================================
// Target definition for synthetic data generation
// ============================================================
typedef struct {
    double amplitude;      // signal amplitude
    int    range_bin;      // expected peak bin in range dimension
    int    doppler_bin;    // expected peak bin in Doppler dimension
} radar_target_t;

// ============================================================
// generate_iq_frame()
//
// Creates a synthetic FMCW beat signal for N targets.
// Each target produces a complex sinusoid in range (fast time)
// and a separate sinusoid in Doppler (slow time).
//
// Output format per sample: [31:16]=Im (int16), [15:0]=Re (int16)
// ============================================================
void generate_iq_frame(uint32_t *buf, int nr, int nd,
                       radar_target_t *targets, int n_targets)
{
    // Scale factor: keep values in int16 range with headroom
    double scale = 8000.0 / n_targets;

    for (int m = 0; m < nd; m++) {           // for each chirp
        for (int n = 0; n < nr; n++) {       // for each sample
            double re_sum = 0.0, im_sum = 0.0;

            for (int k = 0; k < n_targets; k++) {
                // Beat frequency phase across range
                double phase_r = 2.0 * PI * targets[k].range_bin * n / nr;
                // Doppler phase across chirps
                double phase_d = 2.0 * PI * targets[k].doppler_bin * m / nd;
                double phase   = phase_r + phase_d;

                re_sum += targets[k].amplitude * cos(phase);
                im_sum += targets[k].amplitude * sin(phase);
            }

            // Add small AWGN noise (optional — comment out if unwanted)
            re_sum += ((double)rand() / RAND_MAX - 0.5) * 100.0;
            im_sum += ((double)rand() / RAND_MAX - 0.5) * 100.0;

            // Quantize to int16
            int16_t re = (int16_t)(re_sum * scale);
            int16_t im = (int16_t)(im_sum * scale);

            // Pack into 32-bit word: [31:16]=Im, [15:0]=Re
            buf[m * nr + n] = ((uint32_t)(uint16_t)im << 16) |
                               (uint32_t)(uint16_t)re;
        }
    }
}

// ============================================================
// software_fft()
//
// Minimal in-place radix-2 DIT FFT in C (float).
// Used as software reference for correctness checking.
// x_re, x_im: input/output arrays of length n (must be power of 2)
// ============================================================
void software_fft(double *x_re, double *x_im, int n)
{
    // Bit-reversal permutation
    int j = 0;
    for (int i = 1; i < n; i++) {
        int bit = n >> 1;
        for (; j & bit; bit >>= 1) j ^= bit;
        j ^= bit;
        if (i < j) {
            double tmp;
            tmp = x_re[i]; x_re[i] = x_re[j]; x_re[j] = tmp;
            tmp = x_im[i]; x_im[i] = x_im[j]; x_im[j] = tmp;
        }
    }

    // FFT butterfly stages
    for (int len = 2; len <= n; len <<= 1) {
        double ang = -2.0 * PI / len;
        double wr = cos(ang), wi = sin(ang);
        for (int i = 0; i < n; i += len) {
            double cr = 1.0, ci = 0.0;
            for (int k = 0; k < len / 2; k++) {
                double ur = x_re[i+k],        ui = x_im[i+k];
                double vr = x_re[i+k+len/2],  vi = x_im[i+k+len/2];
                double tr = vr*cr - vi*ci,     ti = vr*ci + vi*cr;
                x_re[i+k]         = ur + tr;
                x_im[i+k]         = ui + ti;
                x_re[i+k+len/2]   = ur - tr;
                x_im[i+k+len/2]   = ui - ti;
                double ncr = cr*wr - ci*wi;
                ci = cr*wi + ci*wr;
                cr = ncr;
            }
        }
    }
}

// ============================================================
// run_software_reference()
//
// Runs pure-software Range FFT + magnitude on the same input.
// Returns allocated array of uint32 magnitude values.
// Caller must free().
// ============================================================
uint32_t* run_software_reference(uint32_t *input_buf, int nr, int nd,
                                  double *elapsed_ms)
{
    uint32_t *sw_mag = (uint32_t*)malloc(nr * nd * sizeof(uint32_t));
    if (!sw_mag) { perror("malloc"); return NULL; }

    double *x_re = (double*)malloc(nr * sizeof(double));
    double *x_im = (double*)malloc(nr * sizeof(double));

    struct timespec t_start, t_end;
    clock_gettime(CLOCK_MONOTONIC, &t_start);

    for (int m = 0; m < nd; m++) {
        // Unpack I/Q samples for this chirp
        for (int n = 0; n < nr; n++) {
            uint32_t samp = input_buf[m * nr + n];
            x_re[n] = (double)(int16_t)(samp & 0xFFFF);
            x_im[n] = (double)(int16_t)(samp >> 16);
        }

        // Run FFT
        software_fft(x_re, x_im, nr);

        // Compute magnitude
        for (int n = 0; n < nr; n++) {
            double mag2 = x_re[n]*x_re[n] + x_im[n]*x_im[n];
            // Clamp to uint32 range
            if (mag2 > (double)0xFFFFFFFF) mag2 = (double)0xFFFFFFFF;
            sw_mag[m * nr + n] = (uint32_t)mag2;
        }
    }

    clock_gettime(CLOCK_MONOTONIC, &t_end);
    *elapsed_ms = (t_end.tv_sec - t_start.tv_sec) * 1000.0 +
                  (t_end.tv_nsec - t_start.tv_nsec) / 1e6;

    free(x_re);
    free(x_im);
    return sw_mag;
}

// ============================================================
// find_peak_bin()
//
// Finds the index of the maximum value in an array.
// Used to verify detected range bin matches expected.
// ============================================================
int find_peak_bin(uint32_t *row, int n)
{
    int peak = 0;
    for (int i = 1; i < n; i++)
        if (row[i] > row[peak]) peak = i;
    return peak;
}

// ============================================================
// main()
// ============================================================
int main(void)
{
    printf("==============================================\n");
    printf("  FMCW Radar Range-Doppler SoC — COE838\n");
    printf("==============================================\n\n");

    // ----------------------------------------------------------
    // Step 1: Open /dev/mem and mmap both bridges
    // ----------------------------------------------------------
    int fd = open("/dev/mem", O_RDWR | O_SYNC);
    if (fd < 0) { perror("open /dev/mem"); return 1; }

    // Lightweight bridge — control registers
    void *lw_virtual = mmap(NULL, LW_BRIDGE_SPAN,
                             PROT_READ | PROT_WRITE,
                             MAP_SHARED, fd, LW_BRIDGE_BASE);
    if (lw_virtual == MAP_FAILED) { perror("mmap lw bridge"); return 1; }

    // Full bridge — bulk SRAM
    void *hf_virtual = mmap(NULL, HF_BRIDGE_SPAN,
                             PROT_READ | PROT_WRITE,
                             MAP_SHARED, fd, HF_BRIDGE_BASE);
    if (hf_virtual == MAP_FAILED) { perror("mmap hf bridge"); return 1; }

    // Pointers to our specific components
    // CTRL_SLAVE_0_BASE is defined in hps_0.h from QSys
    void *ctrl_base  = (uint8_t*)lw_virtual + CTRL_SLAVE_0_BASE;
    void *isram_base = (uint8_t*)hf_virtual + INPUT_SRAM_OFFSET;
    void *osram_base = (uint8_t*)hf_virtual + OUTPUT_SRAM_OFFSET;

    printf("[1] Bridges mapped OK\n");
    printf("    LW bridge virtual: %p\n", lw_virtual);
    printf("    HF bridge virtual: %p\n", hf_virtual);

    // ----------------------------------------------------------
    // Step 2: Reset the accelerator
    // ----------------------------------------------------------
    MMIO_WRITE(ctrl_base, CTRL_OFFSET, CTRL_RESET_BIT);
    usleep(1000);  // hold reset for 1ms
    MMIO_WRITE(ctrl_base, CTRL_OFFSET, 0);
    usleep(1000);
    printf("[2] Accelerator reset\n");

    // ----------------------------------------------------------
    // Step 3: Generate synthetic I/Q frame
    // ----------------------------------------------------------
    uint32_t *input_buf = (uint32_t*)malloc(NR * ND * sizeof(uint32_t));
    if (!input_buf) { perror("malloc input"); return 1; }

    // Define 2 targets at known range/Doppler bins
    radar_target_t targets[] = {
        { .amplitude = 1.0, .range_bin = 32,  .doppler_bin = 8  },
        { .amplitude = 0.7, .range_bin = 100, .doppler_bin = 20 }
    };
    int n_targets = 2;

    srand(42);  // fixed seed for reproducibility
    generate_iq_frame(input_buf, NR, ND, targets, n_targets);
    printf("[3] Synthetic I/Q frame generated (%d chirps x %d samples)\n",
           ND, NR);
    printf("    Target 0: range_bin=%d, doppler_bin=%d\n",
           targets[0].range_bin, targets[0].doppler_bin);
    printf("    Target 1: range_bin=%d, doppler_bin=%d\n",
           targets[1].range_bin, targets[1].doppler_bin);

    // ----------------------------------------------------------
    // Step 4: Write I/Q frame into FPGA input SRAM
    // ----------------------------------------------------------
    printf("[4] Writing input frame to FPGA SRAM...\n");
    uint32_t *isram_ptr = (uint32_t*)isram_base;
    for (int i = 0; i < NR * ND; i++) {
        alt_write_word(isram_ptr + i, input_buf[i]);
    }
    printf("    Written %d words (%d KB)\n",
           NR * ND, (NR * ND * 4) / 1024);

    // ----------------------------------------------------------
    // Step 5: Configure and start accelerator
    // ----------------------------------------------------------
    MMIO_WRITE(ctrl_base, NR_OFFSET, NR);
    MMIO_WRITE(ctrl_base, ND_OFFSET, ND);

    printf("[5] Starting accelerator (NR=%d, ND=%d)...\n", NR, ND);

    struct timespec hw_t_start, hw_t_end;
    clock_gettime(CLOCK_MONOTONIC, &hw_t_start);

    MMIO_WRITE(ctrl_base, CTRL_OFFSET, CTRL_START_BIT);

    // ----------------------------------------------------------
    // Step 6: Poll STATUS.DONE
    // ----------------------------------------------------------
    uint32_t status;
    int poll_count = 0;
    do {
        status = MMIO_READ(ctrl_base, STATUS_OFFSET);
        poll_count++;
        if (poll_count > 10000000) {
            printf("ERROR: Accelerator timed out!\n");
            goto cleanup;
        }
    } while (!(status & STATUS_DONE_BIT));

    clock_gettime(CLOCK_MONOTONIC, &hw_t_end);

    double hw_elapsed_ms =
        (hw_t_end.tv_sec - hw_t_start.tv_sec) * 1000.0 +
        (hw_t_end.tv_nsec - hw_t_start.tv_nsec) / 1e6;

    uint32_t hw_cycles = MMIO_READ(ctrl_base, CYCLES_OFFSET);
    printf("[6] Hardware DONE\n");
    printf("    FPGA cycle count : %u cycles\n", hw_cycles);
    printf("    Wall-clock time  : %.3f ms\n", hw_elapsed_ms);

    // ----------------------------------------------------------
    // Step 7: Read results from output SRAM
    // ----------------------------------------------------------
    uint32_t *hw_mag = (uint32_t*)malloc(NR * ND * sizeof(uint32_t));
    if (!hw_mag) { perror("malloc hw_mag"); goto cleanup; }

    uint32_t *osram_ptr = (uint32_t*)osram_base;
    for (int i = 0; i < NR * ND; i++) {
        hw_mag[i] = alt_read_word(osram_ptr + i);
    }
    printf("[7] Results read from FPGA output SRAM\n");

    // ----------------------------------------------------------
    // Step 8: Run software reference
    // ----------------------------------------------------------
    printf("[8] Running software reference...\n");
    double sw_elapsed_ms = 0.0;
    uint32_t *sw_mag = run_software_reference(input_buf, NR, ND,
                                               &sw_elapsed_ms);
    printf("    SW wall-clock time : %.3f ms\n", sw_elapsed_ms);

    // ----------------------------------------------------------
    // Step 9: Validate peak bins
    // ----------------------------------------------------------
    printf("\n=== CORRECTNESS CHECK ===\n");
    int pass = 1;

    for (int m = 0; m < ND; m++) {
        uint32_t *hw_row = hw_mag + m * NR;
        uint32_t *sw_row = sw_mag + m * NR;
        int hw_peak = find_peak_bin(hw_row, NR);
        int sw_peak = find_peak_bin(sw_row, NR);

        if (hw_peak != sw_peak) {
            printf("  MISMATCH chirp %d: HW peak=%d SW peak=%d\n",
                   m, hw_peak, sw_peak);
            pass = 0;
        }
    }

    // Check target 0 detected at correct range bin in first chirp
    int hw_peak0 = find_peak_bin(hw_mag, NR);
    printf("Target 0 expected range bin: %d  HW detected: %d  %s\n",
           targets[0].range_bin, hw_peak0,
           (hw_peak0 == targets[0].range_bin) ? "[PASS]" : "[FAIL]");

    printf("All chirp peaks match SW reference: %s\n",
           pass ? "[PASS]" : "[FAIL — see mismatches above]");

    // ----------------------------------------------------------
    // Step 10: Performance report
    // ----------------------------------------------------------
    printf("\n=== PERFORMANCE REPORT ===\n");
    printf("  Frame size         : %d chirps x %d samples\n", ND, NR);
    printf("  HW FPGA cycles     : %u\n", hw_cycles);
    printf("  HW wall-clock      : %.3f ms\n", hw_elapsed_ms);
    printf("  SW wall-clock      : %.3f ms\n", sw_elapsed_ms);
    if (hw_elapsed_ms > 0)
        printf("  Speedup (SW/HW)    : %.2fx\n",
               sw_elapsed_ms / hw_elapsed_ms);
    printf("  HW throughput      : %.1f frames/sec\n",
           1000.0 / hw_elapsed_ms);

    free(hw_mag);
    free(sw_mag);

cleanup:
    free(input_buf);
    munmap(lw_virtual, LW_BRIDGE_SPAN);
    munmap(hf_virtual, HF_BRIDGE_SPAN);
    close(fd);

    printf("\nDone.\n");
    return 0;
}
