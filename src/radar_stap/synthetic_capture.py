"""Write a *synthetic* DCA1000-style capture so the hardware path can be exercised without hardware.

Produces, in one directory:
  * ``adc_data.bin``    raw 16-bit words in an explicitly chosen :class:`AdcFormat`
  * ``synthetic.cfg``   mmWave-SDK-style CLI configuration describing the waveform
  * ``capture.yaml``    capture configuration (format marked verified *by construction*)
  * ``truth.json``      scene ground truth and quantisation details

The scene comes from a simulation config; each frame reuses the same scene
(platform restarts at its initial position) with a fresh noise realisation.
Samples are quantised to ``adc_bits`` with the noise standard deviation per I/Q
component set to ``noise_lsb`` codes, then clipped to full scale.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import yaml

from .adc_loader import AdcFormat, encode_cube
from .config import SimulationConfig, config_to_dict, sim_derived
from .mmwave_cfg import write_mmwave_cfg
from .simulator import simulate
from .waveforms import complex_noise

DEFAULT_FORMAT = dict(
    sign_handling="int16_twos_complement",
    byte_order="little",
    iq_order="I_first",
    complex_packing="two_sample_blocks",
    channel_layout="rx_planar_per_chirp",
)


def make_synthetic_capture(
    cfg: SimulationConfig,
    output_dir: str | Path,
    num_frames: int = 2,
    adc_bits: int = 16,
    noise_lsb: float = 4.0,
    fmt_overrides: dict | None = None,
    stap_enabled: bool = True,
) -> dict:
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)
    radar = cfg.radar
    M = len(cfg.array.rx_positions)
    fmt = AdcFormat(
        data_type=radar.sampling,
        adc_bits=adc_bits,
        num_rx=M,
        num_adc_samples=radar.num_adc_samples,
        chirps_per_frame=radar.num_chirps,
        num_frames=num_frames,
        **{**DEFAULT_FORMAT, **(fmt_overrides or {})},
    )
    fmt.validate()
    sim = simulate(cfg)
    clean = sim.data - sim.components["noise"]
    rng = np.random.default_rng(np.random.SeedSequence([cfg.seed, 4242]))
    comp_std = np.sqrt(radar.noise_power / 2)
    scale = noise_lsb / comp_std
    lim = (1 << (adc_bits - 1)) - 1
    frames, clip = [], 0
    for _ in range(num_frames):
        n = complex_noise(rng, clean.shape, radar.noise_power, np.complex128)
        x = clean + (n if radar.sampling == "complex" else n.real)
        q = np.rint(np.real(x) * scale) + (1j * np.rint(np.imag(x) * scale) if radar.sampling == "complex" else 0)
        clip += int(np.sum(np.abs(np.real(q)) > lim) + np.sum(np.abs(np.imag(q)) > lim))
        q = np.clip(np.real(q), -lim - 1, lim) + 1j * np.clip(np.imag(q), -lim - 1, lim)
        frames.append(np.transpose(q, (1, 0, 2)))  # (chirps, rx, samples)
    cube = np.stack(frames)
    (out / "adc_data.bin").write_bytes(encode_cube(cube, fmt))

    d = sim_derived(cfg)
    rx_mask = (1 << M) - 1
    loops = d.num_loops
    waveform = {
        "carrier_frequency_hz": radar.carrier_frequency_hz,
        "chirp_slope_hz_per_s": radar.chirp_slope_hz_per_s,
        "idle_time_s": radar.idle_time_s,
        "adc_start_time_s": radar.adc_start_time_s,
        "ramp_end_time_s": radar.ramp_end_time_s,
        "adc_sample_rate_hz": radar.adc_sample_rate_hz,
    }
    cfg_text = write_mmwave_cfg(waveform, radar.num_adc_samples, rx_mask, cfg.array.tx_schedule, loops, num_frames,
                                1e3 * max(d.cpi_duration_s * 2, 1e-3), adc_bits, radar.sampling == "complex")
    (out / "synthetic.cfg").write_text(cfg_text, encoding="utf-8")

    fmt_yaml = {k: v for k, v in fmt.as_dict().items()
                if k not in ("num_rx", "num_adc_samples", "chirps_per_frame", "adc_bits", "data_type")}
    stap = config_to_dict(cfg.stap)
    stap.update({"enabled": stap_enabled, "loading_mode": "noise_eig_relative", "exclude_known_targets": False})
    capture_yaml = {
        "notes": "SYNTHETIC capture generated by radar_stap.synthetic_capture; format verified by construction.",
        "capture_format_verified": True,
        "adc_format": fmt_yaml,  # remaining fields come from synthetic.cfg
        "waveform": {"mmwave_cfg_file": "synthetic.cfg", "mixer_convention": radar.mixer_convention},
        "antenna": {
            "verified": True,
            "position_units": cfg.array.position_units,
            "rx_positions": cfg.array.rx_positions,
            "tx_positions": cfg.array.tx_positions,
        },
        # synthetic channels are ideal (no gain/phase errors): unit calibration
        "rx_calibration": [[1.0, 0.0]] * (M * len(cfg.array.tx_schedule)),
        "platform_velocity_mps": cfg.platform.velocity_mps,
        "processing": config_to_dict(cfg.processing),
        "detection": config_to_dict(cfg.detection),
        "stap": stap,
    }
    with open(out / "capture.yaml", "w", encoding="utf-8") as fh:
        yaml.safe_dump(capture_yaml, fh, sort_keys=False)
    info = {
        "truth": sim.metadata["truth"],
        "scale_codes_per_unit": scale,
        "noise_lsb_per_component": noise_lsb,
        "clipped_values": clip,
        "num_frames": num_frames,
        "bytes": (out / "adc_data.bin").stat().st_size,
        "adc_format": fmt.as_dict(),
        "scenario": cfg.scenario_name,
    }
    (out / "truth.json").write_text(json.dumps(info, indent=2), encoding="utf-8")
    return info
